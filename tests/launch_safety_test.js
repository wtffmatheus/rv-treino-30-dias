'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const load = file => fs.readFileSync(path.join(root, file), 'utf8')
const config = load('assets/js/config.js')
const checkout = load('assets/js/checkout.js')
const landing = load('assets/js/projeto.js')
const student = load('assets/js/area.js')
const cardio = load('assets/js/cardio.js')

assert.match(config, /salesEnabled:\s*false/)
assert.match(config, /productionAccessVerified:\s*false/)
assert.match(config, /paymentUrl:\s*''/)
assert.match(checkout, /config\.salesEnabled === true/)
assert.match(checkout, /config\.productionAccessVerified === true/)
assert.match(landing, /function salesReady\(course\)/)
assert.match(landing, /updateSalesStatus\(\)/)
assert.match(landing, /button\.disabled = true/)
assert.match(landing, /CONFIG\.salesEnabled === true/)
assert.match(landing, /CONFIG\.productionAccessVerified === true/)
assert.match(checkout, /const productionMisconfigured = !config\.testMode && !productionReady/)
assert.match(student, /localStorage\.getItem\(marker\)/)
assert.match(student, /localStorage\.setItem\(marker, '1'\)/)
assert.match(cardio, /if \(key && save\.checked\)/)
assert.match(cardio, /localStorage\.removeItem\(key\)/)
const asset = load('assets/data/rv30-videos-template.json')
const manifest = JSON.parse(asset)
assert.equal(manifest.items.length, 30)
assert(manifest.items.every(item => item.driveUrl === ''))
console.log('Launch safeguards: venda desligada, matrícula não presumida, privacidade de FC e Drive preservados.')
