'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {inventory,privateOutput}=require('../scripts/prepare-private-videos')
const {files,assertPublishableFiles}=require('../scripts/site-files')
const mixed=inventory(['12.MOV','1.mov','2.mp4','30.webm','aula 03.m4v'])
assert.deepEqual(mixed.items.map(x=>x.day),[1,2,3,12,30])
assert(mixed.missingDays.includes(4),'uma lacuna não renumera os outros dias')
const duplicate=inventory(['1.mov','01.mp4','2.mov','12 - versão 2.mp4','31.mov'])
assert.deepEqual(duplicate.conflicts,[1])
assert.deepEqual(duplicate.items.map(x=>x.day),[2])
assert.equal(duplicate.rejected.length,2)
for(const output of ['assets/media','public/videos','dist/videos','.'])assert.throws(()=>privateOutput(output),/pasta fora|output\//)
const destination=privateOutput('output/private-video-test')
assert(destination.endsWith('private-video-test'))
fs.rmdirSync(destination)
assert(!files.some(file=>/manifest\.private|rv30-media|\.mov$|dia-\d+.*\.mp4$/i.test(file)),'mídia e manifesto privados não podem entrar no build')
for(const leaked of ['assets/30.MOV','assets/dia-01.mp4','assets/manifest.private.json','assets/upload-receipt.private.json'])assert.throws(()=>assertPublishableFiles([leaked]),/bloqueado/)
assert.doesNotThrow(()=>assertPublishableFiles(['assets/brand/rv30-logo.png']))
assert(fs.readFileSync(path.join(__dirname,'../.gitignore'),'utf8').includes('output/'))
console.log('Preparação privada: ordem, lacunas, conflitos, nomes ambíguos e exclusão do build verificados. Sem envio remoto.')
